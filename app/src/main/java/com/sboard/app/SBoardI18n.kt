    fun initialize(context: Context) {
        if (initialized) return
        mode.value = context.getSharedPreferences("sboard_ui", Context.MODE_PRIVATE)
            .getString("language", "system") ?: "system"
        initialized = true
    }

    fun setLanguage(context: Context, value: String) {
        require(value in setOf("system", "ru", "en"))
        mode.value = value
        context.getSharedPreferences("sboard_ui", Context.MODE_PRIVATE)
            .edit().putString("language", value).apply()
    }

    fun currentMode(): String = mode.value

    fun isEnglish(): Boolean = when (mode.value) {
        "en" -> true
        "ru" -> false
        else -> Locale.getDefault().language != "ru"
    }

    fun tr(russian: String): String = if (isEnglish()) english[russian] ?: russian else russian
}

fun tr(russian: String): String = SBoardI18n.tr(russian)
